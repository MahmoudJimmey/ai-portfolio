def esc(s): return html.escape(s, quote=True)

def stage_media(base):
    out = []
    for key, p in PROJECTS.items():
        if p["fit"] == "ui":
            rows = [("Canonical tags", "Pass"), ("Broken internal links", "3 found"), ("Core Web Vitals, mobile", "Needs work"),
                    ("Rank, primary keyword", "Up 4"), ("Uptime, last 24 hours", "100%"), ("Weekly summary", "Sent")]
            items = "".join(f'<tr><td>{esc(a)}</td><td>{esc(b)}</td></tr>' for a, b in rows)
            out.append(f'<figure class="shot ui" data-p="{key}" data-s="0" data-ui><figcaption>Sample audit layout</figcaption><table>{items}</table></figure>')
            continue
        for i, s in enumerate(p["slides"]):
            if s.startswith("video:"):
                v = s[6:]
                out.append(f'<video class="shot cover" data-p="{key}" data-s="{i}" src="{base}img/{v}.mp4" poster="{base}img/{v}_poster.jpg" width="720" height="900" muted loop playsinline preload="none" aria-label="Me presenting an Autologist video about Lamborghini, muted"></video>')
                continue
            out.append(f'<img class="shot {p["fit"]}" data-p="{key}" data-s="{i}" src="{base}img/{s}.jpg" width="1080" height="1350" alt="{esc(p["alt"])}"{"" if key=="scoopbot" and i==0 else " loading=\"lazy\""}>')
    return "\n".join(out)

